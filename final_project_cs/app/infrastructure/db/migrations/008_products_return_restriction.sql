-- ★상품 자체가 갖는 반품 제한을 담는다 (2026-09-03).
--
--   `return_refund` 는 "제공된 주문·반품 이력·**정책 근거상** 반품 요청을
--   검토할 수 있습니다" 라고 답하면서, 실제로는 (1) 진행 중인 반품이 있는가
--   (2) 반품 기간이 지났는가 **둘만** 봤다. 코퍼스에 있는 반품 제한
--   (`13_return_restrictions.md` 청약철회 제한, `08_order_cancel-timing.md`
--   주문제작)은 evidence 로 받아만 오고 판단에 쓰지 않았다
--   (docs/reports/debugs/2026-09-03_반품제한을_안_보고_정책근거상_가능하다고_답한다.md).
--
--   볼 데이터가 없었기 때문이다 — `products` 에 이 자리가 없었다.
--
-- ★**NULL 을 허용하고, NULL 은 "모른다" 다** (`returns.order_item_id` 와 같은
--   규약, 007). 이미 쌓인 상품 행에는 제한 정보가 없고, 지금 와서 'none' 으로
--   채우면 **"제한 없음" 을 지어내는 것**이다. 모르면 모른다고 답해야 한다.
--
--     NULL            아직 확인되지 않음 → 제한 없음이라고 단정하지 않는다
--     'none'          제한 없음이 **확인됨**
--     그 밖의 코드     제한 있음 (예: 'made_to_order')
--
-- ★상품 자체의 속성만 담는다. 청약철회 제한 사유 중 "사용·일부 소비로 가치가
--   감소한 경우" 같은 것은 **배송 후 물건 상태**에 달렸지 상품 속성이 아니다.
--   그건 이 컬럼으로 판정하지 않는다 — 사람이 본다.
--
-- ★러너가 모든 SQL 을 이어붙여 한 트랜잭션에 돌린다. 재실행해도 안전해야
--   여기서 죽지 않고 뒤 마이그레이션까지 적용된다.
ALTER TABLE products ADD COLUMN IF NOT EXISTS return_restriction text;

COMMENT ON COLUMN products.return_restriction IS
    'NULL=모름, none=제한없음 확인, 그 밖=제한 코드(made_to_order 등). 상품 속성만.';
